#!/usr/bin/env bash
# scripts/dependency-security-fixes.sh - Auto-create security fix PRs
# Scan repositories for vulnerable dependencies and create fix PRs
set -uo pipefail

source "$(dirname "$0")/../lib/config.sh"
source "$(dirname "$0")/../lib/telegram.sh"

log "=== Dependency Security Fixes ==="

# Configuratie
DSF_ENABLED="${DSF_ENABLED:-yes}"
DSF_DRY_RUN="${DSF_DRY_RUN:-no}"
DSF_CREATE_PR="${DSF_CREATE_PR:-yes}"

# Function: scan for vulnerable packages
scan_vulnerable_deps() {
  local repo="$1"
  
  log "  Scanning $repo for vulnerable dependencies..."
  
  # Check for different lock files
  local vulns=""
  
  # npm audit
  if [ -f "$REPOS_DIR/${repo//\//_}/package-lock.json" ] && command -v npm &>/dev/null; then
    log "  Running npm audit..."
    cd "$REPOS_DIR/${repo//\//_}"
    vulns=$(npm audit --json 2>/dev/null | python3 -c "
import sys, json
try:
  data = json.load(sys.stdin)
  for vuln in data.get('vulnerabilities', {}).values():
    if vuln.get('severity') in ['high', 'critical']:
      print(f\"{vuln.get('name', 'unknown')}|{vuln.get('severity', 'unknown')}|{vuln.get('url', '')}\")
except:
  pass
" 2>/dev/null || echo "")
  fi
  
  # pip-audit for Python
  if [ -f "$REPOS_DIR/${repo//\//_}/requirements.txt" ] && command -v pip-audit &>/dev/null; then
    log "  Running pip-audit..."
    cd "$REPOS_DIR/${repo//\//_}"
    vulns=$(pip-audit -r requirements.txt --format json 2>/dev/null | python3 -c "
import sys, json
try:
  data = json.load(sys.stdin)
  for vuln in data.get('vulns', []):
    for affected in vuln.get('affected', []):
      print(f\"{vuln.get('id', 'unknown')}|{vuln.get('description', 'unknown')}|{vuln.get('id', '')}\")
except:
  pass
" 2>/dev/null || echo "")
  fi
  
  echo "$vulns"
}

# Function: run npm audit fix
create_npm_fix_pr() {
  local repo="$1"
  local branch_name="fleet/security-fix-npm-$(date +%s)"
  
  log "  Creating npm security fix PR..."
  
  if [ "$DSF_DRY_RUN" = "yes" ]; then
    log "    [DRY RUN] Would create PR: $branch_name"
    return 0
  fi
  
  local repo_dir="$REPOS_DIR/${repo//\//_}"
  cd "$repo_dir"
  
  # Create branch
  git checkout -b "$branch_name" 2>/dev/null || true
  
  # Run npm audit fix
  npm audit fix --force 2>/dev/null || npm audit fix 2>/dev/null || true
  
  # Commit
  git add package*.json 2>/dev/null || true
  if git diff --cached --quiet; then
    log "    ℹ️ Geen wijzigingen na npm audit fix"
    git checkout main 2>/dev/null || true
    git branch -D "$branch_name" 2>/dev/null || true
    return 1
  fi
  
  git commit -m "fix: Security vulnerabilities resolved by npm audit

Auto-generated by Fleet Manager dependency-security-fixes.sh

Vulnerabilities addressed:
- High/critical issues from npm audit" 2>/dev/null || true
  
  # Push and create PR
  git push origin "$branch_name" 2>/dev/null || true
  
  gh pr create --repo "$repo" \
    --title "Security: Fix vulnerable npm dependencies" \
    --body "Auto-generated security fix PR from Fleet Manager.

Run \`npm audit\` in your local environment to review all changes." \
    2>/dev/null || log "    ❌ PR creation mislukt"
  
  # Switch back
  git checkout main 2>/dev/null || true
  log "    ✅ Security fix PR aangemaakt"
}

# Function: create pip fix PR
create_pip_fix_pr() {
  local repo="$1"
  local branch_name="fleet/security-fix-pip-$(date +%s)"
  
  log "  Creating pip security fix PR..."
  
  if [ "$DSF_DRY_RUN" = "yes" ]; then
    log "    [DRY RUN] Would create PR: $branch_name"
    return 0
  fi
  
  local repo_dir="$REPOS_DIR/${repo//\//_}"
  cd "$repo_dir"
  
  # Create branch
  git checkout -b "$branch_name" 2>/dev/null || true
  
  # Update requirements.txt
  if command -v pip-audit &>/dev/null; then
    pip-audit --fix --skip-editable 2>/dev/null || true
  fi
  
  # Commit
  git add requirements*.txt 2>/dev/null || true
  if git diff --cached --quiet; then
    log "    ℹ️ Geen wijzigingen na pip-audit fix"
    git checkout main 2>/dev/null || true
    git branch -D "$branch_name" 2>/dev/null || true
    return 1
  fi
  
  git commit -m "fix: Security vulnerabilities resolved by pip-audit

Auto-generated by Fleet Manager dependency-security-fixes.sh" 2>/dev/null || true
  
  # Push and create PR
  git push origin "$branch_name" 2>/dev/null || true
  
  gh pr create --repo "$repo" \
    --title "Security: Fix vulnerable pip dependencies" \
    --body "Auto-generated security fix PR from Fleet Manager.

Run \`pip-audit\` in your local environment to review all changes." \
    2>/dev/null || log "    ❌ PR creation mislukt"
  
  # Switch back
  git checkout main 2>/dev/null || true
  log "    ✅ Security fix PR aangemaakt"
}

# Hoofdlogica
if [ "$DSF_ENABLED" != "yes" ]; then
  log "Dependency security fixes uitgeschakeld"
  exit 0
fi

for kr in "${KEY_REPOS[@]}"; do
  repo_name="${kr##*/}"
  repo_dir="$REPOS_DIR/${kr//\//_}"
  
  if [ ! -d "$repo_dir" ]; then
    log "⚠️  Repo niet gekloond: $kr"
    continue
  fi
  
  log "Checking $kr for security vulnerabilities..."
  
  # Determine dependency type
  has_npm=false
  has_pip=false
  
  [ -f "$repo_dir/package-lock.json" ] || [ -f "$repo_dir/package.json" ] && has_npm=true
  [ -f "$repo_dir/requirements.txt" ] && has_pip=true
  
  if [ "$has_npm" = "true" ] && [ "$DSF_CREATE_PR" = "yes" ]; then
    create_npm_fix_pr "$kr"
  fi
  
  if [ "$has_pip" = "true" ] && [ "$DSF_CREATE_PR" = "yes" ]; then
    create_pip_fix_pr "$kr"
  fi
  
  if [ "$has_npm" = "false" ] && [ "$has_pip" = "false" ]; then
    log "  ℹ️ Geen package-lock.json of requirements.txt gevonden"
  fi
done

log "=== Dependency Security Fixes klaar ==="
